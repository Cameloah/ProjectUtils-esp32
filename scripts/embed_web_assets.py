#!/usr/bin/env python3
"""Embed the files in web/ into a C++ header so the firmware needs no filesystem image.

Run after changing anything in web/ (the pre-commit hook does this automatically).
Exits with status 1 if the header had to be rewritten, so stale output fails the check.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "pu" / "web_assets.gen.h"
WEB = ROOT / "web"
DELIMITER = "PUWEB"


def constant_name(filename: str) -> str:
    """settings.html -> kWebSettingsHtml"""
    words = re.split(r"[^A-Za-z0-9]+", filename)
    return "kWeb" + "".join(word[:1].upper() + word[1:] for word in words if word)


def render() -> str:
    parts = [
        "// Generated by scripts/embed_web_assets.py from the files in web/. Do not edit.",
        "// clang-format off",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "namespace pu {",
        "",
    ]
    for path in sorted(WEB.iterdir()):
        if not path.is_file():
            continue
        name = constant_name(path.name)
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if f"){DELIMITER}" in text:
            raise ValueError(f"{path} contains the raw string delimiter ){DELIMITER}")
        parts.append(f"// {path.relative_to(ROOT).as_posix()}")
        parts.append(f'static const char {name}[] PROGMEM = R"{DELIMITER}({text}){DELIMITER}";')
        parts.append("")
    parts.append("} // namespace pu")
    parts.append("")
    return "\n".join(parts)


def main() -> int:
    content = render()
    if OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == content:
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"updated {OUTPUT.relative_to(ROOT)}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
